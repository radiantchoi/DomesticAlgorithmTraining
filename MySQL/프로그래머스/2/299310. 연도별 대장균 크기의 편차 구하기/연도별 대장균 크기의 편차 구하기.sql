SELECT YEAR(D.DIFFERENTIATION_DATE) AS YEAR,
M.MAXIMUM - D.SIZE_OF_COLONY AS YEAR_DEV,
D.ID
FROM ECOLI_DATA D
JOIN (
    SELECT YEAR(DIFFERENTIATION_DATE) AS YEAR,
    MAX(SIZE_OF_COLONY) AS MAXIMUM
    FROM ECOLI_DATA
    GROUP BY YEAR
) AS M ON M.YEAR = YEAR(D.DIFFERENTIATION_DATE)
ORDER BY YEAR ASC, YEAR_DEV ASC;